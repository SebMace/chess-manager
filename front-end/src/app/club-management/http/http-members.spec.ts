import { MatchersV3 } from '@pact-foundation/pact';
import { firstValueFrom } from 'rxjs';
import { adapterAgainst, frontEndContract } from '../../../testing/front-end-contract';
import { Member } from '../ports/members';
import { HttpMembers } from './http-members';

const CLUB_ID = '3d9a4e1c-6b2f-4f7a-8c15-0e7b9a2d4f68';

const CAMILLE: Member = {
  firstName: 'Camille',
  lastName: 'Martin',
  ffeId: 'K58213',
  licenseType: 'A',
  elo: 2310,
  fideTitle: 'MF',
};
const ALEX: Member = {
  firstName: 'Alex',
  lastName: 'Durand',
  ffeId: 'K61477',
  licenseType: 'B',
  elo: 1790,
  fideTitle: null,
};

describe('HttpMembers', () => {
  it('fetches the members of a club', () =>
    frontEndContract
      .addInteraction()
      .given('the club G45301 has the member Camille Martin, a FIDE master rated 2310')
      .uponReceiving('a request for the members of a club')
      .withRequest(
        'GET',
        // The identifier of the club is generated by the back-end, which injects it from the provider state.
        MatchersV3.fromProviderState('/api/clubs/${clubId}/members', `/api/clubs/${CLUB_ID}/members`),
      )
      .willRespondWith(200, (response) => response.jsonBody(MatchersV3.eachLike({ ...CAMILLE })))
      .executeTest(async (mockServer) => {
        const members = await firstValueFrom(adapterAgainst(HttpMembers, mockServer.url).ofClub(CLUB_ID));

        expect(members).toEqual([CAMILLE]);
      }));

  it('registers a new member of a club', () =>
    frontEndContract
      .addInteraction()
      .given('the club G45302 is managed by the application')
      .uponReceiving('the registration of a new member of a club')
      .withRequest(
        'POST',
        MatchersV3.fromProviderState('/api/clubs/${clubId}/members', `/api/clubs/${CLUB_ID}/members`),
        (request) => request.jsonBody(requestBodyOf(ALEX)),
      )
      .willRespondWith(201)
      .executeTest(async (mockServer) => {
        await expect(firstValueFrom(adapterAgainst(HttpMembers, mockServer.url).register(CLUB_ID, ALEX)))
          .resolves.toBeNull();
      }));
});

/** The body the back-end expects, written out independently of the adapter under test. */
function requestBodyOf(member: Member) {
  return {
    firstName: member.firstName,
    lastName: member.lastName,
    ffeId: member.ffeId,
    licenseType: member.licenseType,
    elo: member.elo,
    fideTitle: member.fideTitle,
  };
}
